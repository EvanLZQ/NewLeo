"""
Stripe Checkout — a second payment method next to PayPal.

Flow (hosted Stripe Checkout page, no card data ever touches our servers):

1. The storefront creates the UNPAID order exactly as for PayPal
   (create_pending / create_pending_guest — same totals, coupons, shipping,
   customs fee, rounding).
2. POST /api/order/stripe/create_session {order_id}
   Builds a Checkout Session for order.total_amount (USD, in cents) read
   from the database — never from the browser — and returns its URL. The
   browser redirects there.
3. Stripe sends the shopper back to
   <STRIPE_RETURN_BASE_URL>/checkout/stripe/success?session_id=cs_...
   (or /checkout/stripe/cancel). The success page calls
   GET /api/order/stripe/session_status?session_id=..., which asks Stripe
   for the session and, if it is paid, marks the order PAID.
4. Independently, Stripe calls POST /api/order/stripe/webhook (signature
   checked with STRIPE_WEBHOOK_SECRET). checkout.session.completed /
   async_payment_succeeded / payment_intent.succeeded mark the order PAID;
   charge.refunded records the refund. This catches shoppers who close the
   tab before step 3.

Steps 3 and 4 both go through _fulfil(), which locks the order row and is
idempotent: whichever arrives second finds the OrderPayment row and does
nothing. The PAID transition is the same one PayPal's confirmPayment does
(OrderPayment row, frozen ship-to address, payment_status='PAID', paid
items removed from carts, confirmation e-mail).

Everything is configured from the environment (see Leoptique/settings.py
and docs/STRIPE_SETUP.md); with STRIPE_ENABLED off every endpoint answers 404.
"""
import datetime
import json
import logging
from decimal import Decimal

from django.conf import settings
from django.db import transaction
from django.http import HttpResponse, JsonResponse
from django.utils import timezone
from django.views.decorators.csrf import csrf_exempt
from django.views.decorators.http import require_POST
from rest_framework import status
from rest_framework.authentication import SessionAuthentication
from rest_framework.decorators import api_view, authentication_classes, permission_classes
from rest_framework.permissions import AllowAny
from rest_framework.response import Response

from Leoptique.authentication import AccessTokenAuthentication
from .models import CompleteSet, OrderInfo, OrderPayment, OrderUpdates
from .service.order_service import money

logger = logging.getLogger(__name__)

AUTH_CLASSES = [SessionAuthentication, AccessTokenAuthentication]

# Every order is priced and charged in USD (see ORDER_CURRENCY in views.py;
# CAD on the storefront is display only). Stripe reports currencies lower-case.
STRIPE_CURRENCY = 'usd'

# Stripe's minimum Checkout Session lifetime is 30 minutes; a little more so
# a slow Stripe clock never rejects it.
SESSION_LIFETIME = datetime.timedelta(minutes=31)

UPDATE_BY = 'stripe'


# ── Configuration ────────────────────────────────────────────────────────────

def stripe_enabled():
    return bool(settings.STRIPE_ENABLED and settings.STRIPE_SECRET_KEY)


def webhook_enabled():
    return stripe_enabled() and bool(settings.STRIPE_WEBHOOK_SECRET)


def _client():
    import stripe
    return stripe.StripeClient(settings.STRIPE_SECRET_KEY, max_network_retries=2)


def _as_dict(obj):
    return obj.to_dict() if hasattr(obj, 'to_dict') else dict(obj)


# ── Thin wrappers around the Stripe API (the only code that talks to Stripe;
# tests patch these) ──────────────────────────────────────────────────────────

def stripe_create_session(params):
    # Network retries (max_network_retries) reuse one idempotency key
    # generated by the SDK, so a retried request cannot make two sessions.
    return _as_dict(_client().v1.checkout.sessions.create(params=params))


def stripe_retrieve_session(session_id):
    return _as_dict(_client().v1.checkout.sessions.retrieve(session_id))


def stripe_expire_session(session_id):
    return _as_dict(_client().v1.checkout.sessions.expire(session_id))


def verify_webhook(payload, sig_header):
    """Raise ValueError / stripe.SignatureVerificationError if the request
    was not signed by Stripe with our endpoint secret (or is > 5 min old)."""
    import stripe
    stripe.Webhook.construct_event(payload, sig_header, settings.STRIPE_WEBHOOK_SECRET)
    # Use the verified raw JSON as plain dicts.
    return json.loads(payload)


# ── Helpers ──────────────────────────────────────────────────────────────────

def to_cents(amount):
    """Decimal dollars -> integer cents, after the same half-up rounding as
    every stored amount (OrderService money())."""
    return int(money(amount) * 100)


def _note(order, title, details):
    """Leave a note on the order for the admin (deduplicated, so a webhook
    retried by Stripe does not stack copies)."""
    if not OrderUpdates.objects.filter(order=order, title=title[:50], details=details).exists():
        OrderUpdates.objects.create(order=order, title=title[:50], details=details, by=UPDATE_BY)


def _flag(order, title, details):
    OrderInfo.objects.filter(pk=order.pk).update(issue_order=True)
    _note(order, title, details)
    logger.error('Stripe: order %s: %s — %s', order.order_number, title, details)


def expire_sessions_later(session_ids):
    """Called when pending orders are cancelled: once the cancel commits, close
    their open Checkout pages so they can no longer be paid. Best effort."""
    if not stripe_enabled():
        return
    session_ids = [s for s in session_ids if s]
    if not session_ids:
        return

    def _expire():
        for session_id in session_ids:
            try:
                stripe_expire_session(session_id)
            except Exception:
                # Already completed / expired, or Stripe unreachable. A late
                # payment is still recorded and flagged by _fulfil().
                logger.info('Stripe: could not expire session %s', session_id, exc_info=True)

    transaction.on_commit(_expire)


def _caller_order(request, order_id, lock=False):
    """The caller's own order, or None. Same ownership rules as PayPal:
    signed-in -> order.customer; guest -> the order this session created
    (guest_pending_order_id)."""
    qs = OrderInfo.objects.select_for_update() if lock else OrderInfo.objects
    try:
        order_id = int(order_id)
    except (TypeError, ValueError):
        return None
    user = getattr(request, 'user', None)
    if user is not None and user.is_authenticated:
        return qs.filter(pk=order_id, customer=user).first()
    if request.session.get('guest_pending_order_id') != order_id:
        return None
    return qs.filter(pk=order_id, customer=None).first()


def _caller_owns_paid_guest_order(request, order):
    done = request.session.get('guest_completed_order') or {}
    return order.customer_id is None and done.get('order_number') == order.order_number


def _remove_from_carts(order):
    from Customer.models import ShoppingCart
    paid_set_ids = list(CompleteSet.objects.filter(order=order).values_list('id', flat=True))
    if paid_set_ids:
        for cart in ShoppingCart.objects.filter(eyeglasses_set__id__in=paid_set_ids).distinct():
            cart.eyeglasses_set.remove(*paid_set_ids)


def _send_confirmation(order):
    try:
        order.refresh_from_db()
        from Order.email_service import send_order_confirmation
        send_order_confirmation(order)
    except Exception:
        logger.exception('Failed to send order confirmation email for order %s', order.order_number)


# ── Marking an order paid ────────────────────────────────────────────────────

class FulfilResult:
    PAID = 'paid'                # newly marked PAID now
    ALREADY = 'already'          # this Stripe payment was recorded before
    REJECTED = 'rejected'        # money arrived but order not marked (flagged)
    NOT_FOUND = 'not_found'


def _fulfil(order_id, *, session_id, payment_intent_id, amount_cents, currency,
            payer_email, raw):
    """
    Record a successful Stripe payment and mark the order PAID — the same
    transition confirmPayment does for PayPal. Idempotent and safe to call
    concurrently (row lock + OrderPayment lookup).

    amount_cents / currency are what Stripe says it charged; they must equal
    the order's own total in USD, otherwise the order is NOT marked paid and
    is flagged (issue_order + an OrderUpdates note) for a person to sort out.
    Returns (FulfilResult, order or None).
    """
    from .views import _detach_paid_order_address

    try:
        order_id = int(order_id)
    except (TypeError, ValueError):
        return FulfilResult.NOT_FOUND, None

    send_email = False
    with transaction.atomic():
        order = OrderInfo.objects.select_for_update().filter(pk=order_id).first()
        if order is None:
            logger.error('Stripe: paid session %s points at missing order %s', session_id, order_id)
            return FulfilResult.NOT_FOUND, None

        recorded = OrderPayment.objects.filter(payment_gateway='stripe', order=order)
        if (payment_intent_id and recorded.filter(transaction_id=payment_intent_id).exists()) or \
                (session_id and recorded.filter(gateway_transaction_id=session_id).exists()):
            return FulfilResult.ALREADY, order

        expected = to_cents(order.total_amount)
        charged = f'{Decimal(amount_cents or 0) / 100:.2f} {str(currency or "").upper()}'
        ref = payment_intent_id or session_id

        if order.payment_status == 'PAID':
            _flag(order, 'Stripe: duplicate payment',
                  f'Order was already paid ({order.payment_type}); Stripe also charged '
                  f'{charged} ({ref}). Refund one of them in the Stripe Dashboard.')
            return FulfilResult.REJECTED, order

        if str(currency or '').lower() != STRIPE_CURRENCY or amount_cents != expected:
            _flag(order, 'Stripe: amount/currency mismatch',
                  f'Stripe charged {charged} ({ref}) but the order total is '
                  f'{money(order.total_amount)} USD. Not marked paid.')
            return FulfilResult.REJECTED, order

        OrderPayment.objects.create(
            transaction_id=(payment_intent_id or session_id)[:50],
            customer=order.customer,
            order=order,
            payment_gateway='stripe',
            transaction_amount=money(Decimal(amount_cents) / 100),
            currency='USD',
            payer_email=(payer_email or '')[:254],
            gateway_transaction_id=(session_id or '')[:100],
            payment_response=raw or {},
            transaction_status='completed',
        )

        frozen_address = _detach_paid_order_address(order.address)
        update = dict(payment_status='PAID', payment_type='stripe', address=frozen_address)
        if session_id:
            update['stripe_checkout_session_id'] = session_id
        if payment_intent_id:
            update['stripe_payment_intent_id'] = payment_intent_id
        OrderInfo.objects.filter(pk=order.pk).update(**update)

        if order.order_status == 'CANCELED':
            # The pending order was cancelled (shopper started another
            # checkout, or it expired) while its Stripe page was still open,
            # and then they paid. The money is real, so record it, but its
            # items may have moved to another order: a person must check.
            _flag(order, 'Stripe: paid after cancel',
                  f'Stripe payment {charged} ({ref}) arrived after this order was '
                  f'cancelled. Check the items / refund in the Stripe Dashboard.')
        else:
            send_email = True

    _remove_from_carts(order)
    if send_email:
        _send_confirmation(order)
    order.refresh_from_db()
    return FulfilResult.PAID, order


def _fulfil_from_session(session):
    """session: a Checkout Session dict (webhook payload or API response)."""
    if session.get('payment_status') != 'paid':
        return None, None
    metadata = session.get('metadata') or {}
    order_id = metadata.get('order_id')
    payment_intent = session.get('payment_intent')
    if isinstance(payment_intent, dict):
        payment_intent = payment_intent.get('id')
    details = session.get('customer_details') or {}
    return _fulfil(
        order_id,
        session_id=session.get('id', ''),
        payment_intent_id=payment_intent or '',
        amount_cents=session.get('amount_total'),
        currency=session.get('currency'),
        payer_email=details.get('email') or session.get('customer_email') or '',
        raw={
            'source': 'checkout.session',
            'session_id': session.get('id'),
            'payment_intent': payment_intent,
            'amount_total': session.get('amount_total'),
            'currency': session.get('currency'),
            'livemode': session.get('livemode'),
        },
    )


# ── Endpoints ────────────────────────────────────────────────────────────────

def _not_enabled():
    return Response({'error': 'Card payment is not available'}, status=status.HTTP_404_NOT_FOUND)


@api_view(['POST'])
@authentication_classes(AUTH_CLASSES)
@permission_classes([AllowAny])
def createStripeSession(request):
    """
    Create a Stripe Checkout Session for one of the caller's UNPAID orders.

    Request body: { order_id }  (from create_pending / create_pending_guest)
    Response (200): { url, session_id }

    The amount is order.total_amount from the database (already rounded to
    the cent by create_pending) — nothing amount-related is read from the
    request.
    """
    if not stripe_enabled():
        return _not_enabled()

    order_id = request.data.get('order_id')
    previous_session = ''
    with transaction.atomic():
        order = _caller_order(request, order_id, lock=True)
        if order is None:
            return Response({'error': 'Order not found'}, status=status.HTTP_404_NOT_FOUND)
        if order.payment_status == 'PAID':
            return Response({'error': 'Order is already paid'}, status=status.HTTP_400_BAD_REQUEST)
        if order.order_status == 'CANCELED':
            return Response({'error': 'This order was cancelled. Please return to checkout.'},
                            status=status.HTTP_400_BAD_REQUEST)
        amount_cents = to_cents(order.total_amount)
        if amount_cents <= 0:
            return Response({'error': 'Order total must be greater than zero'},
                            status=status.HTTP_400_BAD_REQUEST)

        base = settings.STRIPE_RETURN_BASE_URL
        metadata = {'order_id': str(order.pk), 'order_number': order.order_number}
        description = (
            f'Subtotal ${money(order.sub_total)} + shipping ${money(order.shipping_cost)}'
            f' + duties ${money(order.customs_fee)}'
        )
        payment_intent_data = {
            'description': f'Eyelovewear order {order.order_number}',
            'metadata': metadata,
        }
        if settings.STRIPE_STATEMENT_DESCRIPTOR_SUFFIX:
            payment_intent_data['statement_descriptor_suffix'] = \
                settings.STRIPE_STATEMENT_DESCRIPTOR_SUFFIX[:22]
        params = {
            'mode': 'payment',
            'line_items': [{
                'quantity': 1,
                'price_data': {
                    'currency': STRIPE_CURRENCY,
                    'unit_amount': amount_cents,
                    'product_data': {
                        'name': f'Eyelovewear order {order.order_number}',
                        'description': description,
                    },
                },
            }],
            'client_reference_id': order.order_number,
            'metadata': metadata,
            'payment_intent_data': payment_intent_data,
            'success_url': f'{base}/checkout/stripe/success?session_id={{CHECKOUT_SESSION_ID}}',
            'cancel_url': f'{base}/checkout/stripe/cancel?order_id={order.pk}',
            'expires_at': int((timezone.now() + SESSION_LIFETIME).timestamp()),
        }
        if order.email:
            params['customer_email'] = order.email

        try:
            session = stripe_create_session(params)
        except Exception:
            logger.exception('Stripe: could not create a Checkout Session for order %s',
                             order.order_number)
            return Response({'error': 'Could not start card payment. Please try again or use PayPal.'},
                            status=status.HTTP_502_BAD_GATEWAY)

        previous_session = order.stripe_checkout_session_id
        OrderInfo.objects.filter(pk=order.pk).update(
            stripe_checkout_session_id=session['id'], payment_type='stripe')

    if previous_session and previous_session != session['id']:
        expire_sessions_later([previous_session])

    return Response({'url': session['url'], 'session_id': session['id']}, status=status.HTTP_200_OK)


@api_view(['GET'])
@authentication_classes(AUTH_CLASSES)
@permission_classes([AllowAny])
def stripeSessionStatus(request):
    """
    Called by the storefront's /checkout/stripe/success page.

    Query: session_id=cs_...
    Response (200): { status: 'paid' | 'processing' | 'open' | 'expired' | 'error',
                      order_number, email? }

    Asks Stripe for the session (never trusts the URL), and when it is paid
    marks the order PAID right away — the webhook may arrive later or not at
    all (e.g. not configured yet in test mode).
    """
    if not stripe_enabled():
        return _not_enabled()

    session_id = (request.query_params.get('session_id') or '').strip()
    if not session_id.startswith('cs_'):
        return Response({'error': 'session_id is required'}, status=status.HTTP_400_BAD_REQUEST)

    order = OrderInfo.objects.filter(stripe_checkout_session_id=session_id).first()
    owned = order is not None and (
        _caller_order(request, order.pk) is not None or _caller_owns_paid_guest_order(request, order))
    if not owned:
        return Response({'error': 'Order not found'}, status=status.HTTP_404_NOT_FOUND)

    try:
        session = stripe_retrieve_session(session_id)
    except Exception:
        logger.exception('Stripe: could not retrieve session %s', session_id)
        return Response({'error': 'Could not check the payment with Stripe. Please refresh.'},
                        status=status.HTTP_502_BAD_GATEWAY)

    metadata = session.get('metadata') or {}
    if str(metadata.get('order_id')) != str(order.pk):
        return Response({'error': 'Order not found'}, status=status.HTTP_404_NOT_FOUND)

    if session.get('payment_status') == 'paid':
        result, order = _fulfil_from_session(session)
        if result == FulfilResult.REJECTED:
            return Response({'status': 'error', 'order_number': order.order_number,
                             'error': 'We received your payment but could not match it to '
                                      'this order. Our team has been notified and will contact you.'},
                            status=status.HTTP_200_OK)
        body = {
            'status': 'paid',
            'order_number': order.order_number,
            # For the storefront's GA4 purchase event.
            'total_amount': str(money(order.total_amount)),
            'shipping_cost': str(money(order.shipping_cost)),
        }
        if order.customer_id is None:
            # Same session bookkeeping as confirmPaymentGuest, so the
            # "create an account" form on the confirmation page works.
            request.session.pop('guest_pending_order_id', None)
            request.session.pop('guest_cart_id', None)
            request.session['guest_completed_order'] = {
                'order_number': order.order_number, 'email': order.email}
            body['email'] = order.email
        return Response(body, status=status.HTTP_200_OK)

    if session.get('status') == 'expired':
        state = 'expired'
    elif session.get('status') == 'complete':
        state = 'processing'   # e.g. a delayed (bank) payment method
    else:
        state = 'open'
    return Response({'status': state, 'order_number': order.order_number}, status=status.HTTP_200_OK)


# ── Webhook ──────────────────────────────────────────────────────────────────

def _order_for_payment_intent(payment_intent_id, metadata=None):
    order = None
    if payment_intent_id:
        order = OrderInfo.objects.filter(stripe_payment_intent_id=payment_intent_id).first()
    if order is None and metadata and metadata.get('order_id'):
        order = OrderInfo.objects.filter(pk=metadata.get('order_id')).first()
    if order is None and payment_intent_id:
        payment = OrderPayment.objects.filter(
            payment_gateway='stripe', transaction_id=payment_intent_id).select_related('order').first()
        order = payment.order if payment else None
    return order


def _handle_payment_intent_succeeded(pi):
    metadata = pi.get('metadata') or {}
    if not metadata.get('order_id'):
        return  # not one of ours (e.g. a manual charge in the Dashboard)
    _fulfil(
        metadata['order_id'],
        session_id='',
        payment_intent_id=pi.get('id', ''),
        amount_cents=pi.get('amount_received') or pi.get('amount'),
        currency=pi.get('currency'),
        payer_email=pi.get('receipt_email') or '',
        raw={'source': 'payment_intent', 'payment_intent': pi.get('id'),
             'amount_received': pi.get('amount_received'), 'currency': pi.get('currency'),
             'livemode': pi.get('livemode')},
    )


def _handle_payment_failed(obj, kind):
    metadata = obj.get('metadata') or {}
    order = None
    if metadata.get('order_id'):
        order = OrderInfo.objects.filter(pk=metadata.get('order_id')).first()
    error = (obj.get('last_payment_error') or {}).get('message', '')
    logger.info('Stripe: %s for order %s: %s', kind, getattr(order, 'order_number', '?'), error)
    if order is not None and order.payment_status != 'PAID':
        # Shopper stays on Stripe's page and can try another card; nothing
        # to change on the order. A note helps support answer "why".
        _note(order, 'Stripe: payment failed', f'{kind} {obj.get("id", "")} {error}'.strip())


def _handle_charge_refunded(charge):
    payment_intent_id = charge.get('payment_intent') or ''
    order = _order_for_payment_intent(payment_intent_id, charge.get('metadata'))
    if order is None:
        logger.warning('Stripe: refund for unknown payment intent %s', payment_intent_id)
        return
    refunded = Decimal(charge.get('amount_refunded') or 0) / 100
    full = bool(charge.get('refunded'))
    # refound_amount is numeric(5,2); the exact figure is in the note below.
    stored = min(money(refunded), Decimal('999.99'))
    OrderInfo.objects.filter(pk=order.pk).update(
        refound_status='refunded' if full else 'partially_refunded',
        refound_amount=stored,
    )
    # The OrderPayment ledger row stays as charged. order_status is left to the admin (changing it e-mails the customer).
    _note(order, 'Stripe: refund',
          f'{"Full" if full else "Partial"} refund, total refunded {money(refunded)} '
          f'{str(charge.get("currency", "")).upper()} (charge {charge.get("id", "")}).')


@csrf_exempt
@require_POST
def stripeWebhook(request):
    """
    POST /api/order/stripe/webhook — called by Stripe only.

    400 for a bad signature (Stripe shows it as failed in the Dashboard);
    200 once handled or ignored; 500 on an unexpected error so Stripe retries.
    """
    if not webhook_enabled():
        return HttpResponse(status=404)

    payload = request.body
    sig_header = request.META.get('HTTP_STRIPE_SIGNATURE', '')
    try:
        event = verify_webhook(payload, sig_header)
    except Exception:
        logger.warning('Stripe webhook: signature verification failed')
        return HttpResponse('invalid signature', status=400)

    event_type = event.get('type', '')
    obj = ((event.get('data') or {}).get('object')) or {}
    try:
        if event_type in ('checkout.session.completed', 'checkout.session.async_payment_succeeded'):
            _fulfil_from_session(obj)  # no-op until payment_status == 'paid'
        elif event_type == 'checkout.session.async_payment_failed':
            _handle_payment_failed(obj, event_type)
        elif event_type == 'payment_intent.succeeded':
            _handle_payment_intent_succeeded(obj)
        elif event_type == 'payment_intent.payment_failed':
            _handle_payment_failed(obj, event_type)
        elif event_type == 'charge.refunded':
            _handle_charge_refunded(obj)
        else:
            logger.info('Stripe webhook: ignoring %s', event_type)
    except Exception:
        logger.exception('Stripe webhook: failed to handle %s %s', event_type, event.get('id'))
        return HttpResponse(status=500)

    return JsonResponse({'received': True})
